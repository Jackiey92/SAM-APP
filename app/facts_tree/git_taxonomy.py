"""Deterministic taxonomy records built from a validated template pack.

Approved design baseline 36f9035555c7a016d0f51eb2a266611a36ab5e3f,
F-001 P01 sections 10.2.2 (the taxonomy manifest and one record per
leaf live at fixed repository-relative paths), 10.2.3 (record schema
and serializer are versioned independently; paths are generated by the
host from legal IDs only) and 14.2. P01 does not freeze a full taxonomy
JSON schema, so this module implements only the minimal versioned
wrapper: every payload carries ``schema_version`` (this record family's
own schema, SCHEMA_VERSION) plus ``format_version`` (the git_format
serializer version) as two independent fields that are never merged,
derived from each other, or used one in place of the other, and
otherwise reuses the validated pack semantics without adding any new
business meaning.

Single pure function:

- ``build_taxonomy_records(pack, *, pack_version)`` returns a
  deterministic ordered tuple of ``(relative_path, content_bytes)``:
  the manifest record first, then one leaf record per entry of
  ``pack.leaves`` in declaration order. It performs no file, Git
  object, database, network or model IO.

Preconditions and checks (fail closed):

- ``pack`` must be a ``template_packs.TemplatePack``; the caller
  contract is that it came from ``template_packs.validate_pack``. This
  module re-derives ``template_packs.manifest_document(pack)`` and
  ``template_packs.manifest_digest(...)`` and refuses the pack unless
  the digest still equals ``pack.manifest_sha256`` (TypeError for a
  wrong input type, ValueError for a digest mismatch). No field
  supplied by a model ever rewrites the template.
- ``pack_version`` is an opaque host-issued path ID for the
  ``taxonomy/<pack-version>/`` segment. It is never derived here from
  the pack name and version number; the host passes it in. It only
  feeds git_format.record_path segments through encode_id, so traversal
  characters are encoded into one safe segment; the value is not an
  authorization or authenticity proof. Illegal IDs fail closed, and a
  lone surrogate that cannot encode to UTF-8 is reported as a clear
  illegal-ID ValueError, never leaked as a raw UnicodeEncodeError.

Record shapes:

- manifest: schema_version, format_version, every field of
  template_packs.manifest_document(pack) copied verbatim (declaration
  order of the trunks/leaves arrays preserved, no declared field
  dropped, no new semantic field added), plus the pack's
  manifest_sha256.
- leaf: schema_version, format_version, the pack's name and integer
  version, and the LeafCode's code, trunk, title and scope, plus shape
  only when the leaf carries one (generic-v2 leaves have none). No
  classification inference or other new semantics.

All payloads are serialized with git_format.dumps_record; this module
never concatenates JSON itself.

Boundary (explicitly NOT done here, per P01 sections 10.2-10.5):
nothing is written to any repository, Git object, ref or database;
release/binding gates are untouched (load_released_pack is never
called and the set of available packs does not change); no actor,
policy or authorization is authenticated. Persistence and publishing
belong to the host and the Commit Broker path.
"""
from app.facts_tree import git_format
from app.facts_tree import template_packs

SCHEMA_VERSION = 1


def _check_pack_version(pack_version):
    # Same fail-closed ID legality contract as repository_meta:
    # encode_id performs the real check (non-empty str within the
    # character and encoded-segment budgets); its encoded output is not
    # needed here, only the validation. This proves the value's
    # structure, not that the host actually issued it.
    try:
        git_format.encode_id(pack_version)
    except TypeError:
        raise TypeError("pack_version must be a str") from None
    except UnicodeEncodeError as exc:
        raise ValueError("pack_version is not a legal id: %s" % exc) from None
    except ValueError as exc:
        raise ValueError("pack_version is not a legal id: %s" % exc) from None


def _manifest_payload(pack, document):
    payload = {
        "schema_version": SCHEMA_VERSION,
        "format_version": git_format.FORMAT_VERSION,
    }
    # The validated manifest document enters the record verbatim: the
    # declaration order of the trunks/leaves arrays is part of the
    # manifest, and no declared field is dropped or reinterpreted.
    payload.update(document)
    payload["manifest_sha256"] = pack.manifest_sha256
    return payload


def _leaf_payload(pack, leaf):
    payload = {
        "schema_version": SCHEMA_VERSION,
        "format_version": git_format.FORMAT_VERSION,
        "pack": pack.pack,
        "version": pack.version,
        "code": leaf.code,
        "trunk": leaf.trunk,
        "title": leaf.title,
        "scope": leaf.scope,
    }
    if leaf.shape is not None:
        payload["shape"] = leaf.shape
    return payload


def build_taxonomy_records(pack, *, pack_version):
    """Build the manifest and per-leaf taxonomy records for one pack.

    Returns a tuple of ``(relative_path, content_bytes)`` with the
    manifest first and the leaves in ``pack.leaves`` declaration order;
    every path comes from git_format.record_path and every payload from
    git_format.dumps_record, so repeated calls with the same validated
    pack and the same pack_version produce byte-identical output. The
    result is pure data: building it persists, publishes or binds
    nothing.
    """
    if not isinstance(pack, template_packs.TemplatePack):
        raise TypeError("pack must be a template_packs.TemplatePack")
    document = template_packs.manifest_document(pack)
    if template_packs.manifest_digest(document) != pack.manifest_sha256:
        raise ValueError(
            "pack manifest_sha256 does not match the validated manifest "
            "document; pass the TemplatePack returned by validate_pack")
    _check_pack_version(pack_version)
    records = [(
        git_format.record_path("taxonomy_manifest", pack_version=pack_version),
        git_format.dumps_record(_manifest_payload(pack, document)),
    )]
    for leaf in pack.leaves:
        records.append((
            git_format.record_path(
                "taxonomy_leaf", pack_version=pack_version, leaf_id=leaf.code),
            git_format.dumps_record(_leaf_payload(pack, leaf)),
        ))
    return tuple(records)
